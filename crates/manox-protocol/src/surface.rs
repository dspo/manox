//! The declaration surfaces (L12: "the declared surface is the public
//! contract").
//!
//! Four declaration tables name — verbatim, camelCase wire tags — everything
//! a consumer may rely on across the v2 boundary:
//!
//! | table | declares | spec |
//! |---|---|---|
//! | [`JOURNAL_ENTRIES`] | every `JournalWireEvent` variant (§C.2) | §C.2 |
//! | [`PROJECTION_KEYS`] | every projection key (§E.2, first version: 20) | §E.2 |
//! | [`HOST_EVENTS`] | every `HostEvent` variant (§D.5) | §D.5 |
//! | [`frames()`] | every stream kind + frame payload + end reason (§D.1) | §D.1 |
//!
//! plus the auxiliary call tables ([`CLIENT_CALLS`], [`CLIENT_NOTES`],
//! [`SERVER_CALLS`], [`SERVER_NOTES`]) for the §D.2–D.4 method vocabulary.
//!
//! # Single source, compiler-enforced (C3)
//!
//! Every table except [`PROJECTION_KEYS`] (a runtime key set, cross-checked
//! against the session-core registry by its own test) is generated by one
//! [`wire_surface!`] invocation per wire enum. Each invocation declares, in
//! one list, `(match pattern => wire tag ~ sample value)` per variant and
//! generates three artifacts from it:
//!
//! 1. the `pub const` declaration table,
//! 2. an **exhaustive** wire-tag match — a new enum variant that is not
//!    added to the list is a *compile error* (E0004), not a silently missed
//!    test,
//! 3. the ordered sample constructor the coverage harness walks.
//!
//! Table, tag function, and samples therefore cannot drift apart: they are
//! one list. The previous hand-maintained tables could and did drift —
//! `FRAMES` lacked `followSession` while `StreamKind` named FRAMES as its
//! declaring surface, and the scripted host events rode a fake
//! `FromServer::Response` envelope while production used `FromServer::Host`.
//!
//! Stability rules (L12): a name may be *added* at the tail of a group with
//! a protocol-epoch bump; it may never be renamed or removed outside a
//! deliberate spec revision. The `surface_*_complete` tests in
//! `tests/surface_coverage.rs` walk every list against serde: each sample
//! must serialize with exactly its declared tag and round-trip.

