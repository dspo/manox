/// The scripted conversation: the frame samples as `StreamItem`s, one entry
/// frame per declared journal event (dense seq), and one `StreamEnd` per
/// declared reason — all on the real §D.1 envelope. The coverage harness
/// walks it exactly as a client would consume a live follow stream.
pub fn scripted_session() -> Vec<FromServer> {
    use crate::journal::StreamId;
    let stream_1 = StreamId::new("stream-1");
    let mut out = Vec::new();
    for frame in frame_samples() {
        out.push(FromServer::StreamItem {
            stream_id: stream_1.clone(),
            frame,
        });
    }
    // Then every journal entry, one frame each, dense continuing seq.
    for (i, event) in journal_samples().into_iter().enumerate() {
        out.push(FromServer::StreamItem {
            stream_id: stream_1.clone(),
            frame: StreamFrame::Entry {
                seq: (10 + i) as u64,
                id: format!("e-{}", 10 + i),
                parent_id: Some(format!("e-{}", 9 + i)),
                timestamp: "2026-09-04T00:00:00Z".into(),
                event,
            },
        });
    }
    // Stream lifecycle endings (§D.1 StreamEnd) — one per declared reason,
    // each on its own stream id so the emit-coverage walk sees every
    // end-reason name in a single scripted session.
    let endings = [
        (stream_1, StreamEndReason::Closed),
        (StreamId::new("stream-2"), StreamEndReason::Cancelled),
        (StreamId::new("stream-3"), StreamEndReason::Resync),
        (
            StreamId::new("stream-4"),
            StreamEndReason::Failure {
                code: "gateway/internal".into(),
                message: "scripted failure".into(),
            },
        ),
    ];
    for (stream, reason) in endings {
        out.push(FromServer::StreamEnd {
            stream_id: stream,
            reason,
        });
    }
    out
}

/// The scripted `HostEvent` sequence on the real production envelope
/// (`FromServer::Host`). The former version wrapped host events in
/// `FromServer::Response` outcome payloads — a fake envelope no production
/// sender ever used, which let the emit-coverage proof pass while the real
/// `Host` variant had zero round-trip coverage.
pub fn scripted_host_events() -> Vec<FromServer> {
    host_samples()
        .into_iter()
        .map(|host| FromServer::Host { host })
        .collect()
}

