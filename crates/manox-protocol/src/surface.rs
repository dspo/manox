/// The §D.1 frame vocabulary: the `StreamKind` open frame, the three
/// `StreamFrame` payloads, and the four `StreamEndReason` arms. Mechanical
/// concatenation of the three generated tables — never hand-edited (the
/// former hand-maintained `FRAMES` const lacked `followSession` while
/// `StreamKind` declared FRAMES as its surface).
pub fn frames() -> Vec<&'static str> {
    let mut out = STREAM_KINDS.to_vec();
    out.extend_from_slice(STREAM_FRAMES);
    out.extend_from_slice(STREAM_END_REASONS);
    out
}

